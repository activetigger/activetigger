"""Runtime guards for task `name` declarations.

These tests complement static typing (ty/mypy): they verify that
every registered Celery task / subclass actually conforms to the
`TaskName` Literal, which static checkers cannot guarantee.

Run order note: importing `task_manager` triggers autodiscovery,
so the Celery registry is fully populated before assertions run.
"""

from __future__ import annotations

from typing import get_args

import pytest
import task_manager.celery  # noqa: F401  (import triggers task autodiscovery)
from task_manager.active_tigger_task import AbortableActiveTiggerTask, ActiveTiggerTask, TaskNames
from task_manager.celery import celery_app


@pytest.fixture(scope="module")
def valid_names() -> frozenset[str]:
    return frozenset(list(get_args(TaskNames)) + ["success_callback", "failure_callback"])


def test_auto_callback_task_names_valid(valid_names: frozenset[str]) -> None:
    """Every AutoCallbackTask subclass declares a `name` present in TaskName,
    with no duplicates."""
    seen: dict[str, type] = {}  # name -> declaring class name

    def walk(cls: type, ignore: list[type] = []) -> None:
        for sub in cls.__subclasses__():
            # do not test class generated by celery: those classes are aloso subclasses but have an 'app' attribute
            if "app" not in sub.__dict__:
                # allow to ignore testing metaclass like AbortableActiveTiggerTask
                if sub not in ignore:
                    name = getattr(sub, "name", None)
                    assert isinstance(name, str), (
                        f"{sub.__name__}: `name` must be a str, obtained {name!r}"
                    )
                    assert name in valid_names, (
                        f"{sub.__name__}: name={name!r} invalide "
                        f"(valide task names: {sorted(valid_names)}). "
                        f"All task names must be added in TaskNames Literal."
                    )
                    if name in seen:
                        raise AssertionError(
                            f"Duplicated task name {name!r}: in {seen[name].__name__} and {sub.__name__}. "
                        )
                    seen[name] = sub
                walk(sub)

    walk(ActiveTiggerTask, ignore=[AbortableActiveTiggerTask])


def test_celery_registry_matches_task_name(valid_names: frozenset[str]) -> None:
    """Bidirectional coherence between the Celery registry and TaskName."""
    registered = {
        task_name for task_name in celery_app.tasks if not task_name.startswith("celery.")
    }

    unexpected = registered - valid_names
    assert not unexpected, (
        f"Some Registered tasks are not listed in TaskNames: {sorted(unexpected)}"
    )

    missing = valid_names - registered
    assert not missing, f"Some TaskNames are not registered tasks: {sorted(missing)}"
